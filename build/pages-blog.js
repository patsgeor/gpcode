/* Σύνδεσμος προς σελίδα υπηρεσίας από άρθρο */
function slink(slug, text) {
  return '<a href="' + b + 'services/' + slug + '.html">' + esc(text) + '</a>';
}

/** Πίνακας περιεχομένων από τα H2 του σώματος. */
function toc(body) {
  const heads = [];
  body.replace(/<h2 id="([^"]+)">([\s\S]*?)<\/h2>/g, (m, id, text) => {
    heads.push({ id, text: text.replace(/<[^>]+>/g, '') });
    return m;
  });
  if (heads.length < 3) return '';

  return '<nav class="toc" aria-label="Περιεχόμενα άρθρου">' +
    '<div class="toc-title">Σε αυτό το άρθρο</div><ol>' +
    heads.map(h => '<li><a href="#' + h.id + '">' + h.text + '</a></li>').join('') +
    '</ol></nav>';
}

