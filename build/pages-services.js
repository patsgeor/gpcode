'use strict';

const { icon, esc, D } = require('./templates/layout.js');
const C = require('./templates/components.js');

/* Όλες οι σελίδες υπηρεσιών βρίσκονται στο services/ (βάθος 1).
   `b` οδηγεί στη ρίζα· οι αδελφές υπηρεσίες είναι στον ίδιο φάκελο, άρα χωρίς πρόθεμα. */
const b = '../';

const svc = slug => D.services.find(s => s.slug === slug);

/* Σύνδεσμος προς αδελφή υπηρεσία, με ρητό anchor text */
function xlink(slug, text) {
  return '<a href="' + slug + '.html">' + esc(text) + '</a>';
}

/** Κοινό κέλυφος: hero → περιεχόμενο → FAQ → CTA */
function servicePage(slug, sections, opts) {
  const s = svc(slug);
  const o = opts || {};
  const faqs = D.serviceFaqs[slug] || [];

  const content =
    '<section class="page-hero"><div class="container">' +
    '<span class="eyebrow">' + esc(o.eyebrow || 'Υπηρεσία') + '</span>' +
    '<h1>' + esc(s.h1) + '</h1>' +
    '<p class="lead">' + esc(s.intro) + '</p>' +
    '<div class="page-hero-actions">' +
    '<a class="btn btn-light-solid" href="' + b + 'contact.html">' +
    icon('send-fill') + 'Ζητήστε προσφορά</a>' +
    '<a class="btn btn-ghost-light" href="tel:' + esc(D.contact.phone) + '">' +
    icon('telephone-fill') + esc(D.contact.phoneDisplay) + '</a>' +
    '</div></div></section>' +

    sections +

    (faqs.length
      ? '<section class="section section-subtle"><div class="container">' +
        C.sectionHead('Ερωτήσεις', o.faqTitle || 'Συχνές ερωτήσεις για την υπηρεσία') +
        C.faqAccordion(faqs) +
        '<p class="mt-3 mb-0 small text-muted-2">Γενικότερες ερωτήσεις για κόστος, χρόνο ' +
        'και άδεια χρήσης κώδικα υπάρχουν στη <a href="' + b + 'faq.html">σελίδα συχνών ' +
        'ερωτήσεων</a>.</p>' +
        '</div></section>'
      : '') +

    '<section class="section"><div class="container">' +
    C.ctaBand(b, o.cta) + '</div></section>';

  const graph = [
    C.webPageNode('services/' + slug + '.html', s.name, s.description),
    C.serviceNode(s)
  ];
  if (faqs.length) graph.push(C.faqNode('services/' + slug + '.html', faqs));

  return {
    slug: 'services/' + slug + '.html', depth: 1, navId: slug,
    title: s.title, description: s.description,
    content: content,
    breadcrumbs: [
      { name: 'Αρχική', href: 'index.html' },
      { name: 'Υπηρεσίες', href: 'services.html' },
      { name: s.navLabel }
    ],
    graph: graph
  };
}

